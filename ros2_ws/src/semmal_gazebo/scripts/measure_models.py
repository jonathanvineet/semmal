#!/usr/bin/env python3
"""Measure Fuel models' collision bounding boxes with Gazebo itself and write config/model_catalog.yaml.

The catalog gives each model its local footprint (min/max x, y, z of the collision geometry, model frame,
yaw 0), so generate_world.py can rasterise furniture into the occupancy map and the layout test can check
route clearance, without hand-parsing meshes. Requires the models in the local Fuel cache
(scripts/robot/fetch_models.sh) and runs fully offline after that.

Usage: measure_models.py [--models config/models.yaml] [--out config/model_catalog.yaml]
"""
import argparse
import os
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
SPACING = 40.0  # metres between models so nothing interacts


def measurement_world(models):
    inc = []
    for i, (key, m) in enumerate(models.items()):
        inc.append(f"""
    <include>
      <uri>{m['uri']}</uri>
      <name>{key}</name>
      <pose>{i * SPACING} 0 0 0 0 0</pose>
      <static>true</static>
    </include>""")
    return f"""<?xml version="1.0"?>
<sdf version="1.10">
  <world name="measure">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    {''.join(inc)}
  </world>
</sdf>
"""


def measure(models):
    from gz.math7 import Vector3d  # importing gz.math7 also registers AxisAlignedBox/Pose3d types
    from gz.sim8 import Link, Model, TestFixture, World, world_entity

    with tempfile.NamedTemporaryFile('w', suffix='.sdf', delete=False) as f:
        f.write(measurement_world(models))
        path = f.name
    result = {}

    def on_post(_info, ecm):
        if result:
            return
        world = World(world_entity(ecm))
        for i, key in enumerate(models):
            ent = world.model_by_name(ecm, key)
            if not ent:
                raise RuntimeError(f'model {key} not loaded (is it in the Fuel cache?)')
            mins, maxs = [float('inf')] * 3, [float('-inf')] * 3
            for link_ent in Model(ent).links(ecm):
                link = Link(link_ent)
                box = link.compute_axis_aligned_box(ecm)  # in the LINK frame
                pose = link.world_pose(ecm)
                if box is None or pose is None:
                    continue
                lo, hi = box.min(), box.max()
                # Transform all 8 corners by the link's world pose, then take the world AABB.
                for cx in (lo.x(), hi.x()):
                    for cy in (lo.y(), hi.y()):
                        for cz in (lo.z(), hi.z()):
                            p = pose.rot().rotate_vector(Vector3d(cx, cy, cz)) + pose.pos()
                            for k, v in enumerate((p.x() - i * SPACING, p.y(), p.z())):
                                mins[k], maxs[k] = min(mins[k], v), max(maxs[k], v)
            if mins[0] == float('inf'):
                result[key] = None  # visual-only model
                continue
            result[key] = {'min': [round(v, 3) for v in mins], 'max': [round(v, 3) for v in maxs]}

    fx = TestFixture(path)
    fx.on_post_update(on_post)
    fx.finalize()
    fx.server().run(True, 2, False)
    os.unlink(path)
    return result


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--models', default=os.path.join(PKG, 'config', 'models.yaml'))
    ap.add_argument('--out', default=os.path.join(PKG, 'config', 'model_catalog.yaml'))
    a = ap.parse_args(argv)
    with open(a.models, encoding='utf-8') as f:
        models = yaml.safe_load(f)['models']
    boxes = measure(models)
    lines = ['# GENERATED by semmal_gazebo/scripts/measure_models.py from models.yaml. Do not edit.',
             '# Collision AABB of each model in its own frame (yaw 0), measured by gz-sim. Metres.',
             'models:']
    for key in models:
        b = boxes.get(key)
        if b is None:
            lines.append(f'  {key}: null   # no collision geometry')
        else:
            lines.append(f"  {key}: {{min: {b['min']}, max: {b['max']}}}")
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {a.out} ({len(boxes)} models)')
    for key in models:
        b = boxes.get(key)
        if b:
            print(f"  {key:<22} {b['max'][0] - b['min'][0]:.2f} x {b['max'][1] - b['min'][1]:.2f} x {b['max'][2] - b['min'][2]:.2f} m")
        else:
            print(f'  {key:<22} (no collision)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
